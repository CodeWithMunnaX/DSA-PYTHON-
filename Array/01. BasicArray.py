nums = [10,20,30,40,50,60]

print(nums)

# indexing of array

print(nums[0])  # prints first element
print(nums[1])  # prints second element
print(nums[-1]) # prints last element
print(nums[-2]) # prints second last element
print(nums[2:5]) # prints elements from index 2 to 4



# Sizes

size = len(nums)

for i in range(size):
    print(nums[i] , end = " ")
   